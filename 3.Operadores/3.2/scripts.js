/**
 * OPERADOR DE ASIGNACION
 * 
 * en lugar de hacer esto: a = a + b podemos hacer a += b       SUMA
 * en lugar de hacer esto: a = a - b podemos hacer a -= b       RESTA
 * en lugar de hacer esto: a = a * b podemos hacer a *= b       MULTIPLICACION
 * en lugar de hacer esto: a = a / b podemos hacer a /= b       DIVISION
 */

let a = 10
let b = 4
let c 
c = a+=b

console.log(c)

/**
 * EXPONENCIAL - bastante poco su uso
 * 
 * **   doble asterisco para hacer el potencia
 * 
 * en lugar de hacer esto: a = a ** b podemos hacer a **= b       DIVISION
 */

let d = a**b
console.log(d)