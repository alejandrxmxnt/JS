/**
 * TIPOS DE DATOS
 */

//Me diante el operador typeof nos permite ver que tipo de valor es tipo de dato
//NUMBER - NUMERO
console.log(typeof 50)      //imprimira number
console.log(typeof 50.6)    //imprimira number
//STRING - CADENA DE TEXTO
console.log(typeof "Adrian")    //imprimira string
console.log(typeof 'Adrian')    //imprimira string
console.log(typeof 'a')         //imprimira string // en otros lenguajes esto es tomado como char-caracter en javascript no existe eso
//BOOLEAN - BOLEANO
console.log(typeof true)    //imprimira boolean
console.log(typeof false)    //imprimira boolean
